/**
 * بانک تگ داخلی وابسته به زیر‌دسته. این داده فقط برای مدیریت و پیشنهادهای
 * آینده ذخیره می‌شود و تا زمان تعریف سیاست نمایش، وارد ویترین عمومی نمی‌شود.
 */
export function internalTagsForCategory(categorySlug: string): string[] {
  const parent = CATALOG_CATEGORIES.find(category =>
    category.subcategories.some(sub => sub.slug === categorySlug)
  );
  const sub = parent?.subcategories.find(item => item.slug === categorySlug);
  const contextual = sub
    ? [
        sub.label,
        `${sub.label} خاص`,
        `${sub.label} اقتصادی`,
        `${sub.label} لوکس`,
        `${sub.label} دست‌ساز`,
        `${sub.label} وارداتی`
      ]
    : [];

  return [...new Set([
    ...contextual,
    ...(SPECIAL_TAGS[categorySlug] || []),
    ...(parent ? GROUP_TAGS[parent.slug] || [] : []),
    ...COMMON_TAGS
  ])].sort((a, b) => a.localeCompare(b, 'fa'));
}
